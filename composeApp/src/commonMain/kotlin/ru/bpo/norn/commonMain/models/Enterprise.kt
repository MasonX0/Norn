package ru.bpo.norn.commonMain.models

import kotlinx.serialization.Serializable

/**
 * Модель предприятия - базы практики для студентов
 *
 * Эта модель представляет организацию, на которой студенты проходят практику.
 * Предприятия загружаются из TXT файлов в специальном формате и содержат:
 * - Основную информацию об организации (название, город)
 * - Список руководителей практики с их должностями
 * - Категоризацию по типам (зарубежные, кафедры, структурные подразделения и т.д.)
 *
 * Модель используется для:
 * - Сопоставления студентов с местами практики
 * - Генерации статистики в отчетах по типам предприятий
 * - Автоматического заполнения данных о руководителях практики
 * - Классификации предприятий для различных видов отчетности
 *
 * Формат загрузки из TXT файла:
 * "Название предприятия, город // должность1 ! ФИО1, должность2 ! ФИО2"
 */
@Serializable
data class Enterprise(
    /**
     * Полное официальное название предприятия/организации
     *
     * Должно точно соответствовать названию в договорах и официальных документах.
     * Используется для:
     * - Сопоставления с данными студентов по полю nameOfPracticeBase
     * - Генерации направлений на практику
     * - Создания отчетов и статистики
     * - Отображения в интерфейсе пользователя
     *
     * Примеры:
     * - "ООО «Газпром Межрегионгаз Уфа»"
     * - "Кафедра вычислительной техники и инженерной кибернетики"
     * - "АО «Башнефть-Информ»"
     * - "Управление информационных технологий УГНТУ"
     */
    val name: String,

    /**
     * Город расположения предприятия
     *
     * Может быть null, если город не указан в исходном файле.
     * Используется для:
     * - Определения формы практики (стационарная/выездная)
     * - Географической статистики в отчетах
     * - Планирования логистики и командировок
     * - Группировки предприятий по регионам
     *
     * Стандартные значения: "Уфа", "Москва", "Санкт-Петербург",
     * "Нефтекамск", "Стерлитамак", "Салават"
     */
    val city: String?,

    /**
     * Список руководителей практики от данного предприятия
     *
     * Содержит информацию о сотрудниках предприятия, которые могут
     * выступать наставниками для студентов во время практики.
     *
     * Каждый руководитель включает:
     * - ФИО (полное или в формате И.О.)
     * - Должность на предприятии
     *
     * Список может быть пустым, если руководители не назначены.
     * Используется для автоматического заполнения данных в направлениях.
     */
    val supervisors: List<PracticeSupervisor> = emptyList(),

    // ========== КАТЕГОРИЗАЦИЯ ПРЕДПРИЯТИЙ ==========

    /**
     * Признак зарубежного предприятия
     *
     * Определяет предприятия, расположенные за пределами России.
     * Влияет на:
     * - Статистику в сводных отчетах (отдельная колонка)
     * - Особенности оформления документов (визы, загранпаспорта)
     * - Требования к студентам (знание языков)
     * - Дополнительные согласования с международным отделом
     *
     * По умолчанию: false
     */
    val isForeign: Boolean = false,

    /**
     * Признак предприятий в отдаленных районах (Солуни, Тюлюк, Инзер)
     *
     * Специальная категория для предприятий в труднодоступных районах
     * Республики Башкортостан. Требует особого учета из-за:
     * - Сложной логистики и транспортной доступности
     * - Необходимости организации проживания студентов
     * - Дополнительных расходов на командировки
     * - Особых условий практики
     *
     * По умолчанию: false
     */
    val isSoluniTyulyukInzer: Boolean = false,

    /**
     * Признак кафедры вуза как места практики
     *
     * Определяет, является ли "предприятие" фактически кафедрой вуза.
     * Используется для студентов, проходящих внутривузовскую практику.
     *
     * Особенности кафедральной практики:
     * - Руководитель от кафедры = руководитель от "предприятия"
     * - Упрощенное оформление документов
     * - Фокус на научно-исследовательской работе
     * - Отдельная статистика в отчетах
     *
     * По умолчанию: false
     */
    val isDepartment: Boolean = false,

    /**
     * Признак структурного подразделения вуза
     *
     * Определяет подразделения самого университета (не кафедры):
     * - Управление информационных технологий
     * - Библиотека
     * - Центр дистанционного обучения
     * - Вычислительный центр
     * - Отдел кадров
     *
     * Отличается от кафедр административным характером работы
     * и специфическими задачами практики.
     *
     * По умолчанию: false
     */
    val isUniversitySubdivision: Boolean = false,

    /**
     * Признак базовой кафедры
     *
     * Специальные кафедры, созданные на предприятиях для подготовки
     * кадров под конкретные потребности работодателя.
     *
     * Особенности базовых кафедр:
     * - Совмещение теоретического и практического обучения
     * - Преподаватели - сотрудники предприятия
     * - Практика интегрирована в учебный процесс
     * - Высокие шансы трудоустройства выпускников
     *
     * По умолчанию: false
     */
    val isBaseDepartment: Boolean = false
) {
    /**
     * Возвращает форматированное название предприятия с городом
     *
     * Создает строку для отображения в пользовательском интерфейсе,
     * объединяя название предприятия с городом (если указан).
     *
     * @return Строка в формате "Название предприятия, Город" или просто "Название предприятия"
     *
     * Примеры:
     * - "ООО «Газпром», Уфа"
     * - "Кафедра ВТИК" (если город не указан)
     */
    fun getDisplayName(): String {
        return if (city != null) {
            "$name, $city"
        } else {
            name
        }
    }
}

/**
 * Модель руководителя практики от предприятия/организации
 *
 * Представляет сотрудника предприятия, назначенного наставником студента
 * во время прохождения практики. Руководители загружаются из TXT файлов
 * в составе информации о предприятии.
 *
 * Формат в TXT файле: "должность ! ФИО"
 * Пример: "ст. преподаватель ! И.И. Иванов"
 *
 * Используется для:
 * - Автоматического заполнения направлений на практику
 * - Выбора наставника из доступных кандидатов
 * - Контактной информации в документах
 * - Формирования отчетов о кадровом обеспечении практики
 */
@Serializable
data class PracticeSupervisor(
    /**
     * Полное ФИО руководителя практики
     *
     * Может быть в формате:
     * - "Иванов И.И." (сокращенный)
     * - "Иванов Иван Иванович" (полный)
     * - "И.И. Иванов" (альтернативный порядок)
     *
     * Используется в официальных документах и направлениях.
     */
    val fullName: String,

    /**
     * Должность руководителя на предприятии
     *
     * Официальная должность согласно штатному расписанию предприятия.
     * Примеры:
     * - "ст. преподаватель" (для кафедр)
     * - "Ведущий инженер-программист"
     * - "Начальник отдела ИТ"
     * - "Заместитель директора"
     * - "Главный специалист"
     *
     * Важно для определения уровня компетенций наставника.
     */
    val position: String
) {
    /**
     * Возвращает форматированное представление руководителя
     *
     * Объединяет должность и ФИО в единую строку для отображения
     * в интерфейсе и использования в документах.
     *
     * @return Строка в формате "Должность ФИО"
     *
     * Пример: "ст. преподаватель Иванов И.И."
     */
    fun getDisplayText(): String {
        return "$position $fullName"
    }
}