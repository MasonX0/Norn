package ru.bpo.norn.commonMain.models

import kotlinx.serialization.Serializable

/**
 * Вычисляет курс обучения на основе названия группы
 *
 * Алгоритм:
 * 1. Извлекает год поступления из названия группы (например, "24" из "БПО09-24-01")
 * 2. Преобразует двузначный год в полный (24 → 2024)
 * 3. Рассчитывает курс как: текущий год - год поступления + 1
 *
 * @param groupName название группы в формате "КОД##-ГГ-##"
 * @return курс обучения (от 1 до 6), или 1 по умолчанию при ошибке парсинга
 *
 * Примеры тестирования (для 2025 года):
 * - "БПО09-24-01" → курс 2 (2025 - 2024 + 1)
 * - "ИВТ03-23-02" → курс 3 (2025 - 2023 + 1)
 * - "ПИ09и-21-01" → курс 5 (2025 - 2021 + 1)
 * - "БПО09-25-01" → курс 1 (2025 - 2025 + 1)
 * - "неверный_формат" → курс 1 (по умолчанию)
 */
fun calculateCourseFromGroupName(groupName: String): Int {
    return try {
        // Ищем паттерн года в названии группы (две цифры после дефиса)
        val yearMatch = Regex("""-(\d{2})-""").find(groupName)
        if (yearMatch != null) {
            val twoDigitYear = yearMatch.groupValues[1].toInt()

            // Преобразуем двузначный год в полный (предполагаем 20XX для годов 00-99)
            val fullYear = 2000 + twoDigitYear

            // Получаем текущий год (приблизительно, для расчета)
            // В реальном приложении можно использовать более точный способ получения текущего года
            val currentYear = 2025 // TODO: заменить на актуальный текущий год

            // Рассчитываем курс
            val calculatedCourse = currentYear - fullYear

            // Ограничиваем курс разумными пределами (1-6)
            when {
                calculatedCourse < 1 -> 1
                calculatedCourse > 6 -> 6
                else -> calculatedCourse
            }
        } else {
            1 // По умолчанию первый курс, если не удалось распарсить
        }
    } catch (e: Exception) {
        1 // По умолчанию первый курс при любой ошибке
    }
}

/**
 * Модель данных учебной группы - контейнер для организации студентов
 *
 * Группа представляет собой основную единицу организации студентов в системе.
 * Она объединяет студентов одного курса и направления подготовки,
 * обучающихся по общей программе.
 *
 * Основные функции группы:
 * - Организация студентов по учебным коллективам
 * - Массовые операции над данными студентов
 * - Расчет статистики для отчетов
 * - Группировка при генерации документов
 *
 * Группы создаются автоматически при загрузке Excel файлов со студентами
 * или могут быть созданы вручную через интерфейс.
 *
 * @property name Уникальное название группы
 * @property students Список всех студентов в группе
 * @property codeOfDirection Код направления подготовки по ФГОС
 * @property nameOfDirection Полное название направления подготовки
 * @property course Курс обучения группы (от 1 до 6)
 */
@Serializable
data class Group(
    /**
     * Уникальное название группы
     *
     * Служит первичным ключом для идентификации группы в системе.
     * Должно быть уникальным в рамках всего приложения.
     *
     * Стандартный формат: "КОД##-ГГ-##", где:
     * - КОД - код направления (БПО, ИВТ, ПИ)
     * - ## - номер направления (09, 03, 04)
     * - ГГ - год поступления (21, 22, 23, 24, 25)
     * - ## - номер группы (01, 02, 03)
     *
     * Примеры: "БПО09-24-01", "ИВТ03-23-02", "ПИ09и-25-01"
     */
    val name: String,

    /**
     * Список всех студентов, входящих в данную группу
     *
     * Содержит полную информацию о каждом студенте группы.
     * Список может быть:
     * - Пустым при создании новой группы
     * - Пополняться при загрузке данных из Excel
     * - Изменяться при редактировании данных студентов
     *
     * Все операции со студентами (добавление, удаление, редактирование)
     * выполняются через этот список.
     */
    val students: List<Student>,

    /**
     * Код направления подготовки по классификатору ФГОС ВО
     *
     * Стандартный цифровой код направления высшего образования.
     * Может изменяться администратором при необходимости корректировки.
     *
     * Стандартные коды для IT направлений:
     * - "09.03.01" - Информатика и вычислительная техника (бакалавриат)
     * - "09.03.02" - Информационные системы и технологии (бакалавриат)
     * - "09.03.03" - Прикладная информатика (бакалавриат)
     * - "09.03.04" - Программная инженерия (бакалавриат)
     *
     * По умолчанию: "09.03.01"
     */
    var codeOfDirection: String,

    /**
     * Полное официальное название направления подготовки
     *
     * Название образовательной программы согласно лицензии вуза.
     * Может изменяться для корректировки или обновления информации.
     *
     * Стандартные названия:
     * - "Информатика и вычислительная техника"
     * - "Информационные системы и технологии"
     * - "Программная инженерия"
     * - "Прикладная информатика"
     *
     * По умолчанию: "Технологии искусственного интеллекта в нефтегазовой отрасли"
     */
    var nameOfDirection: String,

    /**
     * Курс обучения группы (от 1 до 6)
     *
     * Определяет текущий курс обучения студентов группы.
     * Рассчитывается автоматически на основе названия группы или может быть установлен вручную.
     *
     * Алгоритм расчета по названию группы:
     * 1. Извлекается год поступления из названия (например, "24" из "БПО09-24-01")
     * 2. Курс = текущий год - (2000 + год поступления) + 1
     *
     * Примеры расчета (для 2025 года):
     * - "БПО09-24-01" → год поступления 2024 → курс 2 (2025 - 2024 + 1)
     * - "ИВТ03-23-02" → год поступления 2023 → курс 3 (2025 - 2023 + 1)
     * - "ПИ09и-21-01" → год поступления 2021 → курс 5 (2025 - 2021 + 1)
     *
     * Может быть изменен администратором для корректировки.
     */
    var course: Int
) {


    // ========== МЕТОДЫ ДЛЯ ПОЛУЧЕНИЯ СТАТИСТИКИ ГРУППЫ ==========

    /**
     * Возвращает общее количество студентов в группе
     *
     * Простой подсчет размера списка студентов.
     * Используется для отображения статистики и валидации данных.
     *
     * @return Количество студентов в группе (0 или положительное число)
     */
    fun getStudentsCount(): Int = students.size

    /**
     * Подсчитывает количество студентов с определенной оценкой за практику
     *
     * Выполняет поиск по точному совпадению строки оценки.
     * Используется для создания статистики результатов защиты в отчетах.
     *
     * @param grade Искомая оценка (например, "отлично", "хорошо", "удовлетворительно")
     * @return Количество студентов с указанной оценкой
     *
     * Пример использования:
     * ```kotlin
     * val excellentCount = group.getCountOfStudentsWithGrade("отлично")
     * val goodCount = group.getCountOfStudentsWithGrade("хорошо")
     * ```
     */
    fun getCountOfStudentsWithGrade(grade: String): Int =
        students.count { it.gradeForPractice == grade }

    /**
     * Конструктор для создания пустой группы с параметрами по умолчанию
     *
     * Используется при создании новых групп через интерфейс.
     * Устанавливает стандартные значения для IT направления.
     * Курс рассчитывается автоматически на основе названия группы.
     *
     * @param name Название группы
     */
    constructor(name: String) : this(
        name = name,
        students = emptyList(),
        codeOfDirection = "09.03.01",
        nameOfDirection = "Технологии искусственного интеллекта в нефтегазовой отрасли",
        course = calculateCourseFromGroupName(name)
    )

    // ========== МЕТОДЫ ДЛЯ РАСЧЕТА СЛОЖНОЙ СТАТИСТИКИ ==========

    /**
     * Рассчитывает детальную статистику группы для сводных отчетов
     *
     * Выполняет комплексный анализ данных группы с учетом:
     * - Типов предприятий (зарубежные, российские, кафедры и т.д.)
     * - Форм обучения и финансирования
     * - Результатов защиты отчетов по практике
     * - Территориального распределения практик
     *
     * Алгоритм работы:
     * 1. Анализирует каждого студента группы
     * 2. Сопоставляет базу практики с предприятиями из справочника
     * 3. Классифицирует по типам предприятий и формам практики
     * 4. Подсчитывает результаты защиты по оценкам
     * 5. Извлекает сроки и тип практики из данных студентов
     *
     * @param enterprises Справочник предприятий для сопоставления баз практики
     * @return Объект GroupStatistics с детальной статистикой группы
     *
     * Пример использования:
     * ```kotlin
     * val enterprises = viewModel.enterprisesList.value
     * val stats = group.calculateStatistics(enterprises)
     * println("Всего студентов: ${stats.totalStudents}")
     * println("На зарубежных предприятиях: ${stats.foreignEnterprises}")
     * ```
     */
    fun calculateStatistics(enterprises: List<Enterprise>): GroupStatistics {
        val totalStudents = students.size
        val foreignStudents = students.count { it.isForeign }
        val paidPracticeStudents = students.count { it.isPaidPractice }

        // Инициализируем счетчики для разных типов предприятий
        var foreignEnterprises = 0
        var rfEnterprises = 0
        var soluniTyulyukInzer = 0
        var departmentStudents = 0
        var universitySubdivisions = 0
        var baseDepartments = 0

        // Анализируем каждого студента и классифицируем его базу практики
        students.forEach { student ->
            // Ищем предприятие в справочнике по названию базы практики студента
            val enterprise = enterprises.find {
                it.name.contains(student.nameOfPracticeBase, ignoreCase = true)
            }

            // Классифицируем предприятие по типу
            when {
                enterprise?.isForeign == true -> foreignEnterprises++
                enterprise?.isSoluniTyulyukInzer == true -> soluniTyulyukInzer++
                enterprise?.isDepartment == true -> departmentStudents++
                enterprise?.isUniversitySubdivision == true -> universitySubdivisions++
                enterprise?.isBaseDepartment == true -> baseDepartments++
                else -> rfEnterprises++ // По умолчанию считаем российским предприятием
            }
        }

        // Извлекаем общую информацию о практике из данных первого студента
        // (предполагается, что все студенты группы имеют одинаковые сроки и тип практики)
        val firstStudent = students.firstOrNull()
        val practiceStartDate = firstStudent?.periodOfPractice?.split("-")?.firstOrNull()?.trim()
            ?: "23.06.2025"
        val practiceEndDate = firstStudent?.periodOfPractice?.split("-")?.lastOrNull()?.trim()
            ?: "06.07.2025"
        val practiceType = firstStudent?.typeOfPractice ?: "учебная"

        return GroupStatistics(
            totalStudents = totalStudents,
            foreignEnterprises = foreignEnterprises,
            rfEnterprises = rfEnterprises,
            soluniTyulyukInzer = soluniTyulyukInzer,
            departmentStudents = departmentStudents,
            universitySubdivisions = universitySubdivisions,
            baseDepartments = baseDepartments,
            paidPracticeStudents = paidPracticeStudents,
            foreignStudents = foreignStudents,
            excellentGrades = getCountOfStudentsWithGrade("отлично"),
            goodGrades = getCountOfStudentsWithGrade("хорошо"),
            satisfactoryGrades = getCountOfStudentsWithGrade("удовлетворительно"),
            notDefended = getCountOfStudentsWithGrade("неудов"),
            practiceStartDate = practiceStartDate,
            practiceEndDate = practiceEndDate,
            practiceType = practiceType
        )
    }
}

/**
 * Статистические данные группы для генерации сводных отчетов
 *
 * Этот класс содержит агрегированную информацию о группе студентов,
 * рассчитанную на основе анализа индивидуальных данных каждого студента
 * и сопоставления с справочником предприятий.
 *
 * Используется для:
 * - Генерации таблиц в сводном отчете по практике
 * - Подсчета общих показателей по кафедре/институту
 * - Анализа эффективности организации практики
 * - Планирования практики на следующий период
 *
 * Все поля являются результатом автоматических вычислений
 * и не редактируются пользователем напрямую.
 */
@Serializable
data class GroupStatistics(
    /**
     * Общее количество студентов в группе
     * Базовый показатель для расчета процентных соотношений
     */
    val totalStudents: Int,

    /**
     * Количество иностранных студентов в группе
     * Выделяется отдельно в статистике согласно требованиям отчетности
     */
    val foreignStudents: Int,

    /**
     * Количество студентов на оплачиваемых местах практики
     * Показатель эффективности трудоустройства и привлекательности специальности
     */
    val paidPracticeStudents: Int,

    // ========== РАСПРЕДЕЛЕНИЕ ПО ТИПАМ ПРЕДПРИЯТИЙ ==========

    /**
     * Студенты, проходящие практику на зарубежных предприятиях
     * Показатель международной интеграции образовательной программы
     */
    val foreignEnterprises: Int,

    /**
     * Студенты на предприятиях Российской Федерации
     * Основная масса студентов, проходящих практику на реальных предприятиях
     */
    val rfEnterprises: Int,

    /**
     * Студенты, проходящие практику в отдаленных районах
     * Специальная категория для районов Солуни, Тюлюк, Инзер
     * Требует особого учета из-за сложной логистики
     */
    val soluniTyulyukInzer: Int,

    /**
     * Студенты, проходящие практику на кафедрах вуза
     * Внутривузовская практика для студентов без внешнего места
     */
    val departmentStudents: Int,

    /**
     * Студенты в структурных подразделениях вуза
     * Практика в административных и учебных подразделениях
     */
    val universitySubdivisions: Int,

    /**
     * Студенты на базовых кафедрах
     * Специальные кафедры, созданные на предприятиях
     */
    val baseDepartments: Int,

    // ========== РЕЗУЛЬТАТЫ ЗАЩИТЫ ОТЧЕТОВ ==========

    /**
     * Количество студентов с оценкой "отлично"
     * Высший балл за защиту отчета по практике
     */
    val excellentGrades: Int,

    /**
     * Количество студентов с оценкой "хорошо"
     * Хороший результат защиты отчета
     */
    val goodGrades: Int,

    /**
     * Количество студентов с оценкой "удовлетворительно"
     * Минимальный положительный результат
     */
    val satisfactoryGrades: Int,

    /**
     * Количество студентов, не защитивших отчет в срок
     * Включает неудовлетворительные оценки и пропуски защиты
     */
    val notDefended: Int,

    // ========== ВРЕМЕННЫЕ РАМКИ ПРАКТИКИ ==========

    /**
     * Дата начала практики в формате "ДД.ММ.ГГГГ"
     * Извлекается из поля periodOfPractice первого студента группы
     * По умолчанию: "23.06.2025"
     */
    val practiceStartDate: String,

    /**
     * Дата окончания практики в формате "ДД.ММ.ГГГГ"
     * Извлекается из поля periodOfPractice первого студента группы
     * По умолчанию: "06.07.2025"
     */
    val practiceEndDate: String,

    /**
     * Тип практики для данной группы
     *
     * Определяется на основе курса обучения и учебного плана:
     * - "учебная" - для 1-2 курса, ознакомительная
     * - "производственная" - для 3-4 курса, по профилю специальности
     * - "преддипломная" - для выпускных курсов, связана с ВКР
     * - "НИР" - научно-исследовательская работа
     *
     * По умолчанию: "учебная"
     */
    val practiceType: String
)