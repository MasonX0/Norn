package ru.bpo.norn.commonMain.models

/**
 * Модель данных студента - центральная сущность системы управления практикой
 *
 * Эта data class содержит всю необходимую информацию о студенте для:
 * - Управления данными студентов и групп
 * - Генерации документов (направления, приказы, отчеты)
 * - Отслеживания прохождения практики
 * - Интеграции с данными предприятий и руководителей
 *
 * Модель поддерживает различные типы студентов (бюджетные, платные, целевые, иностранные)
 * и различные формы практики (стационарная, выездная, оплачиваемая).
 *
 * Данные загружаются из Excel файлов и могут быть отредактированы пользователем
 * через интерфейс приложения.
 */
data class Student(
    // ========== ОСНОВНАЯ ИНФОРМАЦИЯ О СТУДЕНТЕ ==========

    /**
     * Полное ФИО студента в формате "Фамилия И.О." или "Фамилия Имя Отчество"
     *
     * Обязательное поле, используется для:
     * - Отображения в списках и таблицах
     * - Генерации направлений на практику
     * - Создания приказов и отчетов
     * - Поиска и идентификации студента
     *
     * Примеры: "Иванов И.И.", "Петрова Анна Сергеевна"
     */
    val name: String,

    /**
     * Курс обучения студента (от 1 до 6)
     *
     * Определяет:
     * - Уровень подготовки студента
     * - Тип практики (учебная для младших курсов, производственная/преддипломная для старших)
     * - Требования к базе практики
     * - Продолжительность практики
     *
     * Стандартные значения:
     * - 1-2 курс: учебная практика
     * - 3-4 курс: производственная практика
     * - 5-6 курс: преддипломная практика
     */
    val course: Int,

    // ========== ИНФОРМАЦИЯ О НАПРАВЛЕНИИ ПОДГОТОВКИ ==========

    /**
     * Код направления подготовки по ФГОС
     *
     * Стандартный код направления высшего образования, например:
     * - "09.03.01" - Информатика и вычислительная техника (бакалавриат)
     * - "09.04.01" - Информатика и вычислительная техника (магистратура)
     * - "09.06.01" - Информатика и вычислительная техника (аспирантура)
     *
     * Используется для:
     * - Официальной документации
     * - Отчетности в Минобрнауки
     * - Классификации студентов по направлениям
     */
    var codeOfDirection: String,

    /**
     * Полное название направления подготовки
     *
     * Официальное название образовательной программы, например:
     * - "Информатика и вычислительная техника"
     * - "Технологии искусственного интеллекта в нефтегазовой отрасли"
     * - "Программная инженерия"
     *
     * Может изменяться администратором для корректировки или уточнения.
     */
    var nameOfDirection: String,

    /**
     * Учебная группа студента
     *
     * Уникальный идентификатор группы в формате, принятом в учебном заведении.
     * Обычно содержит:
     * - Код направления (БПО, ИВТ, ПИ)
     * - Год поступления (21, 22, 23, 24)
     * - Номер группы (01, 02, 03)
     *
     * Примеры: "БПО09-24-01", "ИВТ-21-02", "ПИ09и-23-01"
     *
     * Используется для группировки студентов и массовых операций.
     */
    val group: String,

    // ========== СПЕЦИАЛЬНЫЕ КАТЕГОРИИ СТУДЕНТОВ ==========

    /**
     * Признак иностранного студента
     *
     * Определяет, является ли студент иностранным гражданином.
     * Влияет на:
     * - Статистику в отчетах (отдельная строка для иностранных студентов)
     * - Особенности оформления документов
     * - Требования к практике (ограничения на зарубежные предприятия)
     * - Визовые и миграционные вопросы
     */
    val isForeign: Boolean,

    // ========== РЕЗУЛЬТАТЫ ПРАКТИКИ ==========

    /**
     * Оценка за практику
     *
     * Итоговая оценка, выставленная после защиты отчета по практике.
     * Стандартные значения:
     * - "отлично" (5)
     * - "хорошо" (4)
     * - "удовлетворительно" (3)
     * - "неудовлетворительно" (2)
     * - "не защитил" или "неудов" - для несвоевременной защиты
     *
     * Используется для статистики результатов в сводных отчетах.
     */
    val gradeForPractice: String,

    // ========== ИНФОРМАЦИЯ О МЕСТЕ ПРАКТИКИ ==========

    /**
     * Полное наименование предприятия - базы практики
     *
     * Официальное название организации, где студент проходит практику.
     * Примеры:
     * - "ООО «Газпром Межрегионгаз Уфа»"
     * - "Кафедра вычислительной техники и инженерной кибернетики"
     * - "АО «Башнефть-Информ»"
     *
     * Должно точно соответствовать названию в договоре о практике.
     * Используется для сопоставления с данными из справочника предприятий.
     */
    val nameOfPracticeBase: String,

    /**
     * Тип практики согласно учебному плану
     *
     * Определяет вид практики в соответствии с ФГОС:
     * - "учебная" - ознакомительная практика на младших курсах
     * - "производственная" - практика по профилю специальности
     * - "преддипломная" - практика для подготовки ВКР
     * - "НИР" - научно-исследовательская работа
     *
     * Влияет на содержание и продолжительность практики.
     */
    val typeOfPractice: String,

    /**
     * Период прохождения практики
     *
     * Календарные даты начала и окончания практики в формате:
     * "с ДД.ММ.ГГГГ г. по ДД.ММ.ГГГГ г."
     *
     * Примеры:
     * - "с 07.04.2025 г. по 18.05.2025 г."
     * - "с 23.06.2025 г. по 06.07.2025 г."
     *
     * Используется для генерации направлений и проверки календарных сроков.
     */
    val periodOfPractice: String,

    // ========== ИНФОРМАЦИЯ ОБ ОБУЧЕНИИ ==========

    /**
     * Форма обучения и источник финансирования
     *
     * Определяет, на какой основе обучается студент:
     * - "бюджетная" / "бюджет" - обучение за счет государственного бюджета
     * - "платная" / "платное" - обучение на коммерческой основе
     * - "целевая" / "целевое" - целевое обучение по направлению от организации
     * - "льготная" / "льготный прием" - льготное поступление
     *
     * Влияет на группировку в приказах и статистику в отчетах.
     */
    val formOfStudy: String,

    /**
     * Признак платного обучения (дублирует formOfStudy в булевом виде)
     *
     * Техническое поле для совместимости и упрощения логики.
     * true - если студент обучается на платной основе
     * false - если на бюджетной или целевой основе
     */
    val withPayment: Boolean,

    /**
     * Признак оплачиваемой практики
     *
     * Определяет, получает ли студент зарплату/стипендию на практике:
     * - true - практика оплачивается предприятием
     * - false - практика без оплаты (стандартный случай)
     *
     * Используется для статистики и специальных отметок в документах.
     * По умолчанию false.
     */
    val isPaidPractice: Boolean = false,

    /**
     * Форма проведения практики
     *
     * Определяет, где территориально проходит практика:
     * - "стационарная" - в том же городе, где расположен вуз
     * - "выездная" - в другом городе/регионе/стране
     *
     * Влияет на:
     * - Документооборот и командировочные расходы
     * - Особенности оформления направления
     * - Статистику в отчетах
     *
     * По умолчанию "стационарная".
     */
    val practiceForm: String = "стационарная",

    /**
     * Город прохождения практики
     *
     * Населенный пункт, где территориально расположена база практики.
     * Примеры: "Уфа", "Москва", "Санкт-Петербург", "Нефтекамск"
     *
     * Используется для:
     * - Определения формы практики (стационарная/выездная)
     * - Статистики по регионам в отчетах
     * - Планирования логистики и командировок
     */
    val cityOfPractice: String,

    // ========== ДОПОЛНИТЕЛЬНАЯ ИНФОРМАЦИЯ О СПЕЦИАЛЬНОСТИ ==========

    /**
     * Наименование специальности/профиля подготовки
     *
     * Более узкая специализация в рамках направления подготовки.
     * Примеры:
     * - "Технологии искусственного интеллекта в нефтегазовой отрасли"
     * - "Программное обеспечение средств вычислительной техники"
     * - "Информационные системы и технологии"
     *
     * Может быть пустым, если специализация не определена.
     */
    val nameOfSpeciality: String,

    /**
     * Краткий код специальности
     *
     * Сокращенное обозначение специальности для внутреннего использования.
     * Примеры: "БПО09", "ИВТ", "ПИ09"
     *
     * Часто используется в названиях групп и внутренней документации.
     */
    val codeOfSpeciality: String,

    // ========== РУКОВОДИТЕЛИ ПРАКТИКИ ==========

    /**
     * ФИО руководителя практики от кафедры
     *
     * Преподаватель кафедры, назначенный руководителем практики от вуза.
     * Отвечает за:
     * - Методическое руководство практикой
     * - Контроль выполнения программы практики
     * - Оценку отчета по практике
     * - Связь с предприятием
     *
     * Формат: "Фамилия И.О." или полное ФИО
     */
    val headOfPracticeFromDepartment: String,

    /**
     * ФИО руководителя практики от предприятия
     *
     * Сотрудник предприятия, назначенный наставником студента.
     * Отвечает за:
     * - Практическое обучение студента
     * - Ознакомление с производственными процессами
     * - Контроль выполнения заданий
     * - Характеристику студента
     *
     * Может быть пустым, если руководитель еще не назначен.
     */
    val headOfPracticeFromPracticeBase: String,

    /**
     * Должность руководителя практики от предприятия
     *
     * Официальная должность наставника на предприятии.
     * Примеры:
     * - "Ведущий инженер-программист"
     * - "Начальник отдела информационных технологий"
     * - "Заместитель директора по IT"
     *
     * Используется в официальных документах и характеристиках.
     */
    val postOfHeadOfPracticeFromPracticeBase: String,

    /**
     * Должность руководителя практики от кафедры
     *
     * Академическая должность преподавателя-руководителя.
     * Примеры:
     * - "ст. преподаватель" (старший преподаватель)
     * - "доцент"
     * - "профессор"
     * - "ассистент"
     *
     * Используется в приказах и направлениях на практику.
     */
    val postOfHeadOfPracticeFromDepartment: String,

    // ========== АДМИНИСТРАТИВНАЯ ИНФОРМАЦИЯ ==========

    /**
     * ФИО директора института/декана факультета
     *
     * Руководитель структурного подразделения вуза, от имени которого
     * издаются приказы и подписываются документы по практике.
     *
     * Примеры:
     * - "Павлова З.Х." - директор института
     * - "Сидоров А.И." - декан факультета
     *
     * Используется для подписи официальных документов.
     */
    val directorName: String,
)
