package ru.bpo.norn.jwmMain.navigation

/**
 * Sealed class для определения всех возможных экранов приложения
 *
 * Использует паттерн Sealed Class для обеспечения типобезопасности навигации.
 * Каждый объект представляет отдельный экран с уникальной функциональностью.
 *
 * Архитектурные преимущества:
 * - Компилятор гарантирует обработку всех возможных экранов в when-конструкциях
 * - Невозможно создать неизвестный тип экрана во время выполнения
 * - Легко добавлять новые экраны без изменения существующего кода
 *
 * @see BottomNavBar для использования Screen5-Screen8
 * @see TopNavBar для использования Screen1-Screen4
 */
sealed class Screen {

    /**
     * Экран "Загруженные данные" (Screen1)
     *
     * Отображает информацию о загруженных в систему данных:
     * - Список загруженных групп студентов
     * - Статистика по каждой группе
     * - Возможность выбора конкретной группы для работы
     * - Кнопки для выполнения операций с данными группы
     *
     * Расположение: TopNavBar (первая кнопка)
     * Иконка: ℹ️ (информация)
     */
    object Screen1 : Screen()

    /**
     * Экран "Сводный отчет" (Screen2)
     *
     * Генерирует и отображает сводные отчеты по всем данным:
     * - Общая статистика по студентам
     * - Распределение по предприятиям
     * - Сводка по направлениям практики
     * - Экспорт отчетов в различные форматы
     *
     * Расположение: TopNavBar (вторая кнопка)
     * Иконка: 📋 (отчет)
     */
    object Screen2 : Screen()

    /**
     * Экран "Направления" (Screen3)
     *
     * Управление направлениями практики:
     * - Создание и редактирование направлений
     * - Назначение студентов на направления
     * - Связывание направлений с предприятиями
     * - Контроль распределения мест
     *
     * Расположение: TopNavBar (третья кнопка)
     * Иконка: 🗺️ (направления)
     */
    object Screen3 : Screen()

    /**
     * Экран "Приказ" (Screen4)
     *
     * Формирование официальных приказов:
     * - Генерация приказов о направлении на практику
     * - Шаблоны документов для различных типов практики
     * - Предварительный просмотр и редактирование
     * - Экспорт в PDF для официального использования
     *
     * Расположение: TopNavBar (четвертая кнопка)
     * Иконка: 📜 (документ/приказ)
     */
    object Screen4 : Screen()

    /**
     * Экран "Списки предприятий" (Screen5)
     *
     * Управление базой данных предприятий:
     * - Загрузка списков предприятий из TXT файлов
     * - Просмотр и редактирование информации о предприятиях
     * - Добавление новых предприятий вручную
     * - Удаление неактуальных записей
     * - Поиск и фильтрация по различным критериям
     *
     * Расположение: BottomNavBar (первая кнопка)
     * Иконка: 🏭 (предприятие)
     */
    object Screen5 : Screen()

    /**
     * Экран "Списки студентов" (Screen6)
     *
     * Центральный экран для работы со студентами:
     * - Загрузка данных из Excel файлов
     * - Просмотр студентов по группам
     * - Редактирование информации о студентах
     * - Управление составом групп
     * - Назначение студентов на практику
     *
     * Расположение: BottomNavBar (вторая кнопка)
     * Иконка: 👨‍🎓 (студент)
     */
    object Screen6 : Screen()

    /**
     * Экран "Ведомости" (Screen7)
     *
     * Работа с документами и ведомостями:
     * - Загрузка PDF файлов заявлений
     * - Генерация различных типов ведомостей
     * - Формирование документов для практики
     * - Предварительный просмотр перед печатью
     * - Массовая обработка документов
     *
     * Расположение: BottomNavBar (третья кнопка)
     * Иконка: 📊 (ведомость/документ)
     */
    object Screen7 : Screen()

    /**
     * Экран "Настройки" (Screen8)
     *
     * Конфигурация приложения и системные настройки:
     * - Выбор базовой директории для файлов
     * - Настройка темы приложения (светлая/темная)
     * - Информация о проекте и разработчиках
     * - Системная информация и версия приложения
     * - Сброс настроек к значениям по умолчанию
     *
     * Расположение: BottomNavBar (четвертая кнопка)
     * Иконка: ⚙️ (настройки)
     */
    object Screen8 : Screen()
}
